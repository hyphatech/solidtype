// The one spelling of a name a user writes, from the name Solid's or
// Kobalte's documentation gives: a capital is an underscore and the lower
// case, a run of capitals one word (isSVG is is_svg), a hyphen an
// underscore, and an OCaml keyword takes a trailing underscore.
//
// ppx_solidtype spells it back by the rule's inverse -- a capital after each
// underscore, but a hyphen after aria_ and data_ -- and by the table each
// generator writes of the names the inverse does not give: a hyphen of
// SVG's, stroke-width, or a run of capitals, isSVG.

export const keywords = new Set([
  "and", "as", "assert", "begin", "class", "constraint", "do", "done", "downto", "effect", "else",
  "end", "exception", "external", "false", "for", "fun", "function", "functor", "if", "in", "include",
  "inherit", "initializer", "lazy", "let", "match", "method", "module", "mutable", "new", "nonrec",
  "object", "of", "open", "or", "private", "rec", "sig", "struct", "then", "to", "true", "try", "type",
  "val", "virtual", "when", "while", "with",
]);

export const snake = (s: string) =>
  s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/([A-Z])([A-Z][a-z])/g, "$1_$2").toLowerCase();

// A name as a user writes it.
export function label(name: string): string {
  const l = snake(name).replace(/-/g, "_");
  return keywords.has(l) ? `${l}_` : l;
}

// The JavaScript name the ppx gives back without a table: what
// ppx_solidtype's [js_name] computes, kept the same here.
export function inverse(l: string): string {
  const bare = l.length > 1 && l.endsWith("_") ? l.slice(0, -1) : l;
  if (/^(aria|data)_/.test(bare)) return bare.replace(/_/g, "-");
  return bare.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

// The table of a generator's names the inverse does not give back, as an
// OCaml module the ppx reads; a name given back two ways is an error.
export function table(names: Map<string, string>, source: string): string {
  const rows = [...names]
    .filter(([l, js]) => inverse(l) !== js)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `(* Each name a user writes that the spelling rule's inverse does not
   give back, with its JavaScript name. Generated by ${source}; never
   edited by hand. *)

let names =
  [
${rows.map(([l, js]) => `    (${JSON.stringify(l)}, ${JSON.stringify(js)});`).join("\n")}
  ]
`;
}

// Adds a name to a generator's map, failing on a second spelling.
export function record(names: Map<string, string>, js: string): string {
  const l = label(js);
  const seen = names.get(l);
  if (seen !== undefined && seen !== js) throw new Error(`${l} is both ${seen} and ${js}`);
  names.set(l, js);
  return l;
}
